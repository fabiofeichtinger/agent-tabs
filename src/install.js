// Native host manifest installer.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_EXTENSION_ID, HOST_NAME } from './constants.js';
import { homeDir, launcherPath } from './paths.js';

const CLI_PATH = fileURLToPath(new URL('../bin/agent-tabs.js', import.meta.url));

// Per-user browser config dirs, relative to ~/Library/Application Support
// (macOS) or ~/.config (Linux). The manifest goes in <dir>/NativeMessagingHosts.
const BROWSERS = {
  darwin: {
    chrome: 'Google/Chrome',
    'chrome-beta': 'Google/Chrome Beta',
    'chrome-dev': 'Google/Chrome Dev',
    'chrome-canary': 'Google/Chrome Canary',
    'chrome-for-testing': 'Google/Chrome for Testing',
    chromium: 'Chromium',
    brave: 'BraveSoftware/Brave-Browser',
    edge: 'Microsoft Edge',
    'edge-beta': 'Microsoft Edge Beta',
    'edge-dev': 'Microsoft Edge Dev',
    arc: 'Arc/User Data',
    vivaldi: 'Vivaldi',
  },
  linux: {
    chrome: 'google-chrome',
    'chrome-beta': 'google-chrome-beta',
    'chrome-dev': 'google-chrome-unstable',
    'chrome-canary': 'google-chrome-canary',
    'chrome-for-testing': 'google-chrome-for-testing',
    chromium: 'chromium',
    brave: 'BraveSoftware/Brave-Browser',
    edge: 'microsoft-edge',
    'edge-beta': 'microsoft-edge-beta',
    'edge-dev': 'microsoft-edge-dev',
    vivaldi: 'vivaldi',
  },
};

function configRoot() {
  if (process.platform === 'darwin') return path.join(os.homedir(), 'Library', 'Application Support');
  return process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config');
}

export function knownBrowsers() {
  const table = BROWSERS[process.platform];
  if (!table) return [];
  return Object.entries(table).map(([name, rel]) => {
    const configDir = path.join(configRoot(), rel);
    return { name, configDir, manifestDir: path.join(configDir, 'NativeMessagingHosts') };
  });
}

export function manifestFor(extensionIds) {
  return {
    name: HOST_NAME,
    description: 'agent-tabs native messaging host',
    path: launcherPath(),
    type: 'stdio',
    allowed_origins: extensionIds.map((id) => `chrome-extension://${id}/`),
  };
}

// Homebrew's node lives at <prefix>/Cellar/<formula>/<version>/bin/node, which
// `brew upgrade` deletes. Prefer the <prefix>/opt/<formula> symlink when it
// currently resolves to the same binary.
export function stableNodePath(execPath = process.execPath) {
  const m = /^(.*)\/Cellar\/([^/]+)\/[^/]+\/bin\/node$/.exec(execPath);
  if (!m) return execPath;
  const optPath = path.join(m[1], 'opt', m[2], 'bin', 'node');
  try {
    if (fs.realpathSync(optPath) === fs.realpathSync(execPath)) return optPath;
  } catch {
    // opt link missing or execPath unreadable: keep the original.
  }
  return execPath;
}

const shQuote = (s) => `'${s.replace(/'/g, `'\\''`)}'`;

// Chrome launches the host without a login shell, so PATH may not contain
// node. Bake in the absolute paths found now.
export function launcherScript(nodePath = stableNodePath(), cliPath = CLI_PATH) {
  return [
    '#!/bin/sh',
    '# Generated by `agent-tabs install`. Chrome starts this without a shell PATH,',
    '# so node and the CLI are referenced by absolute path. Re-run install if they move.',
    `exec ${shQuote(nodePath)} ${shQuote(cliPath)} host "$@"`,
    '',
  ].join('\n');
}

// Returns the list of { target, file } that would be/were written.
export function targets({ browsers = [], targetDirs = [] } = {}) {
  const all = knownBrowsers();
  if (browsers.length || targetDirs.length) {
    const unknown = browsers.filter((b) => !all.some((k) => k.name === b));
    if (unknown.length) {
      throw new Error(`unknown browser(s): ${unknown.join(', ')}. Known: ${all.map((b) => b.name).join(', ')}`);
    }
    return [
      ...all.filter((b) => browsers.includes(b.name)).map((b) => ({ target: b.name, dir: b.manifestDir })),
      ...targetDirs.map((d) => ({ target: 'custom', dir: path.resolve(d) })),
    ];
  }
  return all.filter((b) => fs.existsSync(b.configDir)).map((b) => ({ target: b.name, dir: b.manifestDir }));
}

export function install({ extensionIds = [DEFAULT_EXTENSION_ID], browsers, targetDirs, nodePath = stableNodePath(), dryRun = false } = {}) {
  for (const id of extensionIds) {
    if (!/^[a-p]{32}$/.test(id)) throw new Error(`invalid extension ID "${id}" (expected 32 letters a-p)`);
  }
  const launcher = launcherPath();
  const manifest = manifestFor(extensionIds);
  const list = targets({ browsers, targetDirs });
  const written = [];
  if (!dryRun) {
    fs.mkdirSync(homeDir(), { recursive: true, mode: 0o700 });
    fs.writeFileSync(launcher, launcherScript(nodePath), { mode: 0o755 });
    fs.chmodSync(launcher, 0o755);
  }
  for (const { target, dir } of list) {
    const file = path.join(dir, `${HOST_NAME}.json`);
    if (!dryRun) {
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(file, JSON.stringify(manifest, null, 2) + '\n');
    }
    written.push({ target, file });
  }
  return { launcher, manifest, written };
}

export function uninstall({ targetDirs = [] } = {}) {
  const removed = [];
  const dirs = [...knownBrowsers().map((b) => b.manifestDir), ...targetDirs.map((d) => path.resolve(d))];
  for (const dir of dirs) {
    const file = path.join(dir, `${HOST_NAME}.json`);
    if (fs.existsSync(file)) {
      fs.unlinkSync(file);
      removed.push(file);
    }
  }
  const launcher = launcherPath();
  if (fs.existsSync(launcher)) {
    fs.unlinkSync(launcher);
    removed.push(launcher);
  }
  return { removed };
}

// Inspect one manifest file; returns { file, ok, problems[] }.
export function checkManifest(file, extensionId = DEFAULT_EXTENSION_ID) {
  const problems = [];
  let manifest;
  try {
    manifest = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (err) {
    return { file, ok: false, problems: [`unreadable: ${err.message}`] };
  }
  if (manifest.name !== HOST_NAME) problems.push(`name is "${manifest.name}", expected "${HOST_NAME}"`);
  if (manifest.type !== 'stdio') problems.push('type must be "stdio"');
  if (!path.isAbsolute(manifest.path || '')) problems.push('path must be absolute');
  else {
    try {
      fs.accessSync(manifest.path, fs.constants.X_OK);
    } catch {
      problems.push(`launcher ${manifest.path} missing or not executable`);
    }
  }
  const origin = `chrome-extension://${extensionId}/`;
  if (!manifest.allowed_origins?.includes(origin)) problems.push(`allowed_origins does not include ${origin}`);
  return { file, ok: problems.length === 0, problems, allowedOrigins: manifest.allowed_origins ?? [] };
}
